      IF table_name = 'schema_migrations' THEN
        EXECUTE format('CREATE POLICY groundwork_server ON groundwork.%I FOR SELECT TO groundwork_runtime USING (true)',table_name);
      ELSE
        EXECUTE format('CREATE POLICY groundwork_server ON groundwork.%I TO groundwork_runtime USING (true) WITH CHECK (true)',table_name);
      END IF;
    END IF;
  END LOOP;
END
