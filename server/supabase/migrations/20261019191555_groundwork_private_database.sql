      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA groundwork FROM %I',browser_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA groundwork FROM %I',browser_role);
