export async function zipFiles(entries: { name: string; content: string }[]): Promise<Blob> {
  const JSZip = (await import("jszip")).default;
  const zip = new JSZip();
  for (const e of entries) zip.file(e.name, e.content);
  return zip.generateAsync({ type: "blob" });
}